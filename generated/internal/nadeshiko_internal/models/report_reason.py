def check_report_reason(value: str) -> ReportReason:
    if value in REPORT_REASON_VALUES:
        return cast(ReportReason, value)
    raise TypeError(f"Unexpected value {value!r}. Expected one of {REPORT_REASON_VALUES!r}")
